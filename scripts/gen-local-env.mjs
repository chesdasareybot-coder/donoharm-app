// One-off helper: generates .env.local for a local HackerAI + Ollama install.
// Generates random secrets locally; never commits (covered by .gitignore).
import { randomBytes } from "node:crypto";
import { writeFile } from "node:fs/promises";

const b64 = () => randomBytes(32).toString("base64");

const env = `# Generated by scripts/gen-local-env.mjs (local HackerAI + Ollama setup)
# =============================================================================

# --- AI PROVIDERS ------------------------------------------------------------
# OpenRouter (cloud models). Active when USE_OLLAMA=false.
OPENROUTER_API_KEY=sk-or-v1-placeholder

# OpenAI (only used for moderation; blank = moderation disabled gracefully)
OPENAI_API_KEY=

# Abliteration (optional uncensored provider; blank = disabled)
ABLITERATION_API_KEY=

# --- OLLAMA (local LLM) ------------------------------------------------------
# USE_OLLAMA=true routes ALL model selections to the local Ollama server.
# Flip to false to use OpenRouter with the key above instead.
USE_OLLAMA=true
OLLAMA_BASE_URL=http://localhost:11434/v1
OLLAMA_MODEL=mistral

# --- CONVEX (local deployment; filled in by 'npx convex dev --local --once') --
CONVEX_DEPLOYMENT=
NEXT_PUBLIC_CONVEX_URL=
CONVEX_SERVICE_ROLE_KEY=${b64()}
CONVEX_USER_RESEARCH_SERVICE_KEY=${b64()}

# --- WORKOS (authentication; requires a free workos.com account) -------------
WORKOS_API_KEY=sk_test_placeholder
WORKOS_CLIENT_ID=client_placeholder
WORKOS_AUTH_DOMAIN=api.workos.com
WORKOS_COOKIE_PASSWORD=${b64()}
NEXT_PUBLIC_WORKOS_REDIRECT_URI=http://localhost:3000/callback
ACCOUNT_IDENTITY_HMAC_SECRET=${b64()}
WORKOS_WEBHOOK_SECRET=
INTERCOM_MESSENGER_SECRET=

# --- S3 (file storage; blank = uploads disabled) ------------------------------
AWS_S3_ACCESS_KEY_ID=
AWS_S3_SECRET_ACCESS_KEY=
AWS_S3_REGION=us-east-1
AWS_S3_BUCKET_NAME=
S3_REGIONAL_STORAGE_ENABLED=false

# --- SANDBOX / AGENT MODE (cloud execution; blank = Agent mode disabled) ------
MIOSA_API_KEY=
E2B_API_KEY=
E2B_TEMPLATE=terminal-agent-sandbox

# --- WEB SEARCH (optional) -----------------------------------------------------
# PERPLEXITY_API_KEY=
# JINA_API_KEY=

# --- BASE URL ------------------------------------------------------------------
NEXT_PUBLIC_BASE_URL=http://localhost:3000

# --- CENTRIFUGO (sandbox relay; blank OK for Ask mode) -------------------------
CENTRIFUGO_TOKEN_SECRET=
CENTRIFUGO_WS_URL=ws://localhost:8000/connection/websocket

# --- TRIGGER.DEV (Agent Long mode; blank OK) ------------------------------------
TRIGGER_PROJECT_ID=
TRIGGER_SECRET_KEY=
`;

await writeFile(new URL("../.env.local", import.meta.url), env, "utf8");
console.log("OK: .env.local written with generated secrets");
